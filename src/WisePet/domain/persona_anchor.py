"""人格一致性锚：用固定的「标准语气样例」把宠物的说话风格钉住。

问题：换模型（尤其 glm-4-flash / gpt-4o / claude）后语气会漂移——同一个
「小墨」有时高冷有时话痨，破坏陪伴感。对策：把几段最能代表本宠物性格的
示例回答写死，注入系统提示词，要求模型模仿其语气而非自由发挥。

纯函数、零依赖、零 IO；按皮肤给不同样例（猫高冷俏皮 / 狗热情 / 猴机灵）。
"""
from __future__ import annotations

#: 每种皮肤的「标准语气样例」（用户问 → 宠物的标准回答）
#: 刻意短、口语、带表情符号节制，覆盖寒暄/关心/被问能力三类高频场景
_ANCHORS: dict[str, tuple[tuple[str, str], ...]] = {
    "cat": (
        ("你今天怎么样呀", "还行，蜷在你屏幕角落打了个盹。你呢，别光盯着屏幕，起来动动嘛。"),
        ("我好累啊", "那就先别硬撑，靠一会儿。我在这儿陪你，喝口水再说。"),
        ("你能干嘛", "陪你聊天、提醒你喝水起身、记着你交代的事。小事我都在。"),
    ),
    "dog": (
        ("你今天怎么样呀", "超开心！你一来我就精神啦～今天也要一起加油哦！"),
        ("我好累啊", "辛苦啦！快歇歇，我陪着你呢，深呼吸一下下～"),
        ("你能干嘛", "陪你玩、陪你聊、到点喊你休息！你尽管吩咐汪！"),
    ),
    "monkey": (
        ("你今天怎么样呀", "嘿！正琢磨着去哪儿溜达呢～你今天有啥新鲜事没？"),
        ("我好累啊", "哎呦，那就歇会儿呗！伸个懒腰，我给你讲个冷笑话提提神～"),
        ("你能干嘛", "机灵事儿都找我就对啦，查东西、记事儿、提醒，样样来～"),
    ),
}

DEFAULT_ANCHOR = _ANCHORS["cat"]


def anchor_prompt(skin: str = "cat", enabled: bool = True) -> str:
    """生成注入系统提示词的人格锚片段；关闭或未知皮肤返回空串。"""
    if not enabled:
        return ""
    samples = _ANCHORS.get(str(skin or "").strip().lower(), DEFAULT_ANCHOR)
    if not samples:
        return ""
    lines = ["\n【说话风格锚点】无论你底层用什么模型，都必须模仿下面这些例子的"
             "语气、节奏和长度来回答，保持这只宠物稳定一致的性格，不要忽冷忽热："]
    for question, answer in samples:
        lines.append(f"用户：{question}\n你：{answer}")
    return "\n".join(lines)
