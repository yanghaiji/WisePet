"""WisePet 双平台打包程序（纯标准库，需在目标平台上运行）。

Windows：PyInstaller onedir -> 便携 zip -> NSIS 安装程序（检测到 makensis 时）
macOS  ：PyInstaller .app -> 可选 codesign -> DMG（hdiutil）

PyInstaller 不支持交叉编译：Windows 包只能在 Windows 上打、macOS 包只能在
macOS 上打。一次拿到两端产物用 .github/workflows/build.yml 的双 runner。

    python tools/package.py                    # 打当前平台
    python tools/package.py --target windows   # 显式指定目标平台
    python tools/package.py --no-installer     # 只冻结，不生成 zip / setup / dmg
    python tools/package.py --console          # 保留控制台窗口，便于排查启动问题
    python tools/package.py --dry-run          # 只打印将执行的命令
    python tools/package.py --clean            # 清理临时文件与历史产物
"""
from __future__ import annotations

import argparse
import importlib.util
import os
import platform
import re
import shutil
import struct
import subprocess
import sys
import zipfile
from pathlib import Path

# CI 的 Windows runner 控制台默认 cp1252，中文日志直接 UnicodeEncodeError（真机 CI 踩过）：
# 强制 stdout/stderr 走 UTF-8，个别字符兜底替换，绝不让日志炸掉打包流程
for _stream in (sys.stdout, sys.stderr):
    if _stream is not None and hasattr(_stream, "reconfigure"):
        _stream.reconfigure(encoding="utf-8", errors="replace")

ROOT = Path(__file__).resolve().parents[1]
TMP = ROOT / "tmp" / "packaging"
DIST = ROOT / "dist"
APP = "WisePet"
ENTRY = ROOT / "main.py"
ASSETS = ROOT / "assets"
ICON_SOURCE = ASSETS / "pet" / "cat" / "idle" / "01.png"
BUNDLE_ID = "com.wisepet.desktoppet"

NSIS_TEMPLATE = r"""; Generated by tools/package.py (temporary file, ASCII only)
!define APPNAME "WisePet"
Name "${APPNAME} @VERSION@"
OutFile "@OUTFILE@"
InstallDir "$LOCALAPPDATA\${APPNAME}"
RequestExecutionLevel user
Page directory
Page instfiles
UninstPage uninstConfirm
UninstPage instfiles

Section "Install"
  SetOutPath "$INSTDIR"
  File /r "@SOURCE@\*.*"
  WriteUninstaller "$INSTDIR\Uninstall.exe"
  CreateDirectory "$SMPROGRAMS\${APPNAME}"
  CreateShortcut "$SMPROGRAMS\${APPNAME}\${APPNAME}.lnk" "$INSTDIR\${APPNAME}.exe"
  CreateShortcut "$SMPROGRAMS\${APPNAME}\Uninstall.lnk" "$INSTDIR\Uninstall.exe"
  CreateShortcut "$DESKTOP\${APPNAME}.lnk" "$INSTDIR\${APPNAME}.exe"
  WriteRegStr HKCU "Software\Microsoft\Windows\CurrentVersion\Uninstall\${APPNAME}" "DisplayName" "${APPNAME} @VERSION@"
  WriteRegStr HKCU "Software\Microsoft\Windows\CurrentVersion\Uninstall\${APPNAME}" "DisplayVersion" "@VERSION@"
  WriteRegStr HKCU "Software\Microsoft\Windows\CurrentVersion\Uninstall\${APPNAME}" "InstallLocation" "$INSTDIR"
  WriteRegStr HKCU "Software\Microsoft\Windows\CurrentVersion\Uninstall\${APPNAME}" "UninstallString" "$\"$INSTDIR\Uninstall.exe$\""
SectionEnd

Section "Uninstall"
  Delete "$DESKTOP\${APPNAME}.lnk"
  Delete "$SMPROGRAMS\${APPNAME}\${APPNAME}.lnk"
  Delete "$SMPROGRAMS\${APPNAME}\Uninstall.lnk"
  RMDir "$SMPROGRAMS\${APPNAME}"
  DeleteRegKey HKCU "Software\Microsoft\Windows\CurrentVersion\Uninstall\${APPNAME}"
  RMDir /r "$INSTDIR"
SectionEnd
"""


def log(message: str) -> None:
    print(f"[package] {message}", flush=True)


def fail(message: str) -> None:
    raise SystemExit(f"[package] 错误：{message}")


def run(cmd: list[str], *, dry_run: bool = False) -> None:
    shown = " ".join(f'"{part}"' if " " in str(part) else str(part) for part in cmd)
    print(f"  $ {shown}", flush=True)
    if dry_run:
        return
    code = subprocess.call([str(part) for part in cmd], cwd=ROOT)
    if code != 0:
        fail(f"命令执行失败（退出码 {code}）：{shown}")


def app_version() -> str:
    """从 pyproject.toml 取版本号；不用 tomllib 以兼容 Python 3.10。"""
    text = (ROOT / "pyproject.toml").read_text(encoding="utf-8")
    match = re.search(r'^version\s*=\s*"([^"]+)"', text, re.MULTILINE)
    return match.group(1) if match else "0.0.0"


def arch() -> str:
    machine = platform.machine().lower()
    if machine in {"amd64", "x86_64"}:
        return "x64"
    if machine in {"arm64", "aarch64"}:
        return "arm64"
    return machine or "unknown"


def current_platform() -> str:
    if sys.platform == "win32":
        return "windows"
    if sys.platform == "darwin":
        return "macos"
    return sys.platform


def ensure_project_venv() -> None:
    """用项目内 .venv 执行，保证 PySide6 与解释器同源（AGENT.md 规约 §2.7）。"""
    if os.environ.get("WISEPET_PACKAGE_REEXEC") == "1":
        return
    exe = ROOT / (".venv/Scripts/python.exe" if os.name == "nt" else ".venv/bin/python")
    if not exe.is_file() or Path(sys.prefix).resolve() == (ROOT / ".venv").resolve():
        return
    log(f"切换到项目虚拟环境：{exe}")
    env = dict(os.environ, WISEPET_PACKAGE_REEXEC="1")
    raise SystemExit(subprocess.call(
        [str(exe), str(Path(__file__).resolve()), *sys.argv[1:]], cwd=ROOT, env=env))


def make_icons(*, dry_run: bool) -> dict[str, Path]:
    """用现有的 256px PNG 帧生成 ico / icns，避免为打包引入 Pillow。"""
    icons = {"windows": TMP / f"{APP}.ico", "macos": TMP / f"{APP}.icns"}
    if dry_run:
        return icons
    if not ICON_SOURCE.is_file():
        fail(f"图标素材缺失：{ICON_SOURCE}")
    png = ICON_SOURCE.read_bytes()
    if png[:8] != b"\x89PNG\r\n\x1a\n":
        fail(f"图标素材不是 PNG：{ICON_SOURCE}")
    size = struct.unpack(">I", png[16:20])[0]
    TMP.mkdir(parents=True, exist_ok=True)
    # ICO 允许直接内嵌 PNG；256 写成 0（单字节宽高字段的约定）
    icons["windows"].write_bytes(
        struct.pack("<HHH", 0, 1, 1)
        + struct.pack("<BBBBHHII", size & 0xFF, size & 0xFF, 0, 0, 1, 32, len(png), 22)
        + png)
    # ICNS：一个 PNG chunk 即可，类型按边长选 ic07/ic08/ic09
    kind = {128: b"ic07", 256: b"ic08", 512: b"ic09"}.get(size, b"ic08")
    chunk = kind + struct.pack(">I", len(png) + 8) + png
    icons["macos"].write_bytes(b"icns" + struct.pack(">I", len(chunk) + 8) + chunk)
    log(f"图标已生成（源帧 {size}x{size}）")
    return icons


def freeze(target: str, icon: Path, *, console: bool, dry_run: bool) -> None:
    cmd = [sys.executable, "-m", "PyInstaller",
           "--noconfirm", "--clean", "--onedir",
           "--name", APP,
           "--paths", str(ROOT / "src"),
           "--specpath", str(TMP),
           "--workpath", str(TMP / "build"),
           "--distpath", str(DIST),
           "--icon", str(icon),
           "--console" if console else "--windowed"]
    # jieba 是惰性 import，且自带词典必须随包分发，否则分词能力静默退化
    if importlib.util.find_spec("jieba") is not None:
        cmd += ["--hidden-import", "jieba", "--collect-data", "jieba"]
    if target == "macos":
        cmd += ["--osx-bundle-identifier", BUNDLE_ID]
    cmd.append(str(ENTRY))
    log("冻结 Python + PySide6（onedir）")
    run(cmd, dry_run=dry_run)


def bundle_dir(target: str, *, dry_run: bool) -> Path:
    path = DIST / APP if target == "windows" else DIST / f"{APP}.app"
    if target == "macos" and not path.is_dir() and not dry_run:
        apps = sorted(DIST.glob("*.app"))
        if apps:
            path = apps[0]
    if dry_run:
        return path
    if not path.is_dir():
        fail(f"未找到冻结产物目录：{path}")
    exe = (path / f"{APP}.exe" if target == "windows"
           else path / "Contents" / "MacOS" / APP)
    if not exe.is_file():
        fail(f"未找到可执行文件：{exe}")
    return path


def asset_destination(target: str, bundle: Path) -> Path:
    """与 main.py::_runtime_root() 的冻结候选路径保持一致。"""
    if target == "windows":
        return bundle / "assets"
    resources = bundle / "Contents" / "Resources"
    base = resources if resources.is_dir() else bundle / "Contents" / "MacOS"
    return base / "assets"


def copy_assets(target: str, bundle: Path, *, dry_run: bool) -> None:
    destination = asset_destination(target, bundle)
    log(f"复制运行期素材 -> {destination}")
    if dry_run:
        return
    if destination.exists():
        shutil.rmtree(destination)
    shutil.copytree(ASSETS, destination)
    if not (destination / "pet" / "cat" / "idle" / "01.png").is_file():
        fail(f"素材复制后校验失败：{destination}")


def zip_bundle(bundle: Path, version: str, *, dry_run: bool) -> Path:
    archive = DIST / f"{APP}-{version}-windows-{arch()}.zip"
    log(f"生成便携包 {archive.name}")
    if dry_run:
        return archive
    with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as zf:
        for path in sorted(bundle.rglob("*")):
            if path.is_file():
                zf.write(path, Path(bundle.name) / path.relative_to(bundle))
    return archive


def find_makensis() -> str | None:
    found = shutil.which("makensis")
    if found:
        return found
    for var, default in (("ProgramFiles(x86)", r"C:\Program Files (x86)"),
                         ("ProgramFiles", r"C:\Program Files")):
        candidate = Path(os.environ.get(var, default)) / "NSIS" / "makensis.exe"
        if candidate.is_file():
            return str(candidate)
    return None


def nsis_installer(bundle: Path, version: str, *, dry_run: bool) -> Path | None:
    makensis = find_makensis()
    if makensis is None:
        log("未检测到 NSIS (makensis)，跳过 setup.exe；安装 `choco install nsis` 后可生成")
        return None
    output = DIST / f"{APP}-{version}-windows-{arch()}-setup.exe"
    script = TMP / "installer.nsi"
    if not dry_run:
        script.write_text(
            NSIS_TEMPLATE.replace("@OUTFILE@", str(output))
                         .replace("@SOURCE@", str(bundle))
                         .replace("@VERSION@", version),
            encoding="ascii")
    log(f"生成 Windows 安装程序 {output.name}")
    run([makensis, "/V2", str(script)], dry_run=dry_run)
    return output


def sign_app(bundle: Path, *, dry_run: bool) -> None:
    identity = os.environ.get("WISEPET_CODESIGN_IDENTITY", "").strip()
    if not identity:
        return
    log("对 .app 签名（WISEPET_CODESIGN_IDENTITY）")
    run(["codesign", "--deep", "--force", "--options", "runtime",
         "--sign", identity, str(bundle)], dry_run=dry_run)


def dmg_installer(bundle: Path, version: str, *, dry_run: bool) -> Path:
    output = DIST / f"{APP}-{version}-macos-{arch()}.dmg"
    staging = TMP / "dmg"
    if not dry_run:
        if staging.exists():
            shutil.rmtree(staging)
        staging.mkdir(parents=True)
        shutil.copytree(bundle, staging / bundle.name, symlinks=True)
        (staging / "Applications").symlink_to(Path("/Applications"))
    log(f"生成 macOS 磁盘映像 {output.name}")
    run(["hdiutil", "create", "-volname", APP, "-srcfolder", str(staging),
         "-ov", "-format", "UDZO", str(output)], dry_run=dry_run)
    return output


def size_mb(path: Path) -> float:
    if not path.exists():
        return 0.0
    if path.is_dir():
        return sum(p.stat().st_size for p in path.rglob("*") if p.is_file()) / 1048576
    return path.stat().st_size / 1048576


def clean(version: str) -> None:
    for path in (TMP, DIST / APP, DIST / f"{APP}.app"):
        if path.is_dir():
            shutil.rmtree(path)
        elif path.exists():
            path.unlink()
    for pattern in (f"{APP}-{version}-*.zip", f"{APP}-{version}-*.dmg",
                    f"{APP}-{version}-*.exe"):
        for path in DIST.glob(pattern):
            path.unlink()
    log("已清理临时文件与旧产物")


def main() -> int:
    parser = argparse.ArgumentParser(description="WisePet Windows / macOS 打包程序")
    parser.add_argument("--target", choices=("auto", "windows", "macos"), default="auto",
                        help="目标平台，默认取当前系统")
    parser.add_argument("--no-installer", action="store_true",
                        help="只冻结，不生成 zip / setup.exe / dmg")
    parser.add_argument("--console", action="store_true",
                        help="冻结时保留控制台窗口（排查启动失败用）")
    parser.add_argument("--dry-run", action="store_true", help="只打印将执行的命令")
    parser.add_argument("--clean", action="store_true", help="清理临时文件与历史产物")
    args = parser.parse_args()

    version = app_version()
    if args.clean:
        clean(version)
        return 0

    current = current_platform()
    target = current if args.target == "auto" else args.target
    if current not in ("windows", "macos"):
        fail("仅支持在 Windows / macOS 上打包（Linux 不在项目支持范围内）")
    if target != current and not args.dry_run:
        fail(f"PyInstaller 不支持交叉编译：{target} 包请在 {target} 机器上运行本脚本，"
             "或使用 .github/workflows/build.yml 的双平台 CI")
    log(f"目标 {target} / 架构 {arch()} / 版本 {version}"
        + ("（dry-run）" if args.dry_run else ""))

    if not args.dry_run:
        ensure_project_venv()
        if importlib.util.find_spec("PyInstaller") is None:
            fail("缺少 PyInstaller：请先执行 pip install -r dev-requirements.txt")
        TMP.mkdir(parents=True, exist_ok=True)
        DIST.mkdir(parents=True, exist_ok=True)
        for stale in (DIST / APP, DIST / f"{APP}.app"):
            if stale.is_dir():
                shutil.rmtree(stale)

    icons = make_icons(dry_run=args.dry_run)
    freeze(target, icons[target], console=args.console, dry_run=args.dry_run)
    bundle = bundle_dir(target, dry_run=args.dry_run)
    copy_assets(target, bundle, dry_run=args.dry_run)

    artifacts: list[Path] = [bundle]
    if not args.no_installer:
        if target == "windows":
            artifacts.append(zip_bundle(bundle, version, dry_run=args.dry_run))
            installer = nsis_installer(bundle, version, dry_run=args.dry_run)
            if installer is not None:
                artifacts.append(installer)
        else:
            sign_app(bundle, dry_run=args.dry_run)
            artifacts.append(dmg_installer(bundle, version, dry_run=args.dry_run))

    if not args.dry_run:
        shutil.rmtree(TMP, ignore_errors=True)
    log("产物：")
    for path in artifacts:
        print(f"  - {path}" + ("" if args.dry_run else f"（{size_mb(path):.1f} MB）"),
              flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
