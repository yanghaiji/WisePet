def log(message: str) -> None:
    print(f"[package] {message}", flush=True)


def fail(message: str) -> None:
    raise SystemExit(f"[package] 错误：{message}")


def run(cmd: list[str], *, dry_run: bool = False) -> None:
    shown = " ".join(f'"{part}"' if " " in str(part) else str(part) for part in cmd)
    print(f"  $ {shown}", flush=True)
    if dry_run:
        return
    code = subprocess.call([str(part) for part in cmd], cwd=ROOT)
    if code != 0:
        fail(f"命令执行失败（退出码 {code}）：{shown}")


def app_version() -> str:
    """从 pyproject.toml 取版本号；不用 tomllib 以兼容 Python 3.10。"""
    text = (ROOT / "pyproject.toml").read_text(encoding="utf-8")
    match = re.search(r'^version\s*=\s*"([^"]+)"', text, re.MULTILINE)
    return match.group(1) if match else "0.0.0"


def arch() -> str:
    machine = platform.machine().lower()
    if machine in {"amd64", "x86_64"}:
        return "x64"
    if machine in {"arm64", "aarch64"}:
        return "arm64"
    return machine or "unknown"


def current_platform() -> str:
    if sys.platform == "win32":
        return "windows"
    if sys.platform == "darwin":
        return "macos"
    return sys.platform


def ensure_project_venv() -> None:
    """用项目内 .venv 执行，保证 PySide6 与解释器同源（AGENT.md 规约 §2.7）。

    切换时把 PATH 里 conda 相关目录剥掉：conda 的 Library\\bin 里有 ICU /
    api-ms-win-core 存根等 DLL，PyInstaller 做二进制依赖分析时会顺着 PATH
    把它们收进产物，运行时抢在正确模块之前被加载，报
    「DLL load failed while importing QtCore: 找不到指定的程序」（真机实锤）。
    """
    if os.environ.get("WISEPET_PACKAGE_REEXEC") == "1":
        return
    exe = ROOT / (".venv/Scripts/python.exe" if os.name == "nt" else ".venv/bin/python")
    if not exe.is_file() or Path(sys.prefix).resolve() == (ROOT / ".venv").resolve():
        return
    conda_roots = {str(Path(sys.prefix).resolve()).lower(),
                   str(Path(sys.base_prefix).resolve()).lower()}
    clean_path = os.pathsep.join(
        part for part in os.environ.get("PATH", "").split(os.pathsep)
        if part and not any(part.lower().startswith(root) for root in conda_roots))
    log(f"切换到项目虚拟环境：{exe}（PATH 已剔除 conda 目录，防止混入其 DLL）")
    env = dict(os.environ, WISEPET_PACKAGE_REEXEC="1", PATH=clean_path)
    raise SystemExit(subprocess.call(
        [str(exe), str(Path(__file__).resolve()), *sys.argv[1:]], cwd=ROOT, env=env))


def preflight_runtime() -> None:
    """冻结前自检：当前解释器的 PySide6 必须真能加载（子进程实测 QtCore/QtWidgets）。

    conda 环境用 pip 装 PySide6 时，import 当场就能失败或冻结后才报
    「DLL load failed while importing QtCore」（AGENT.md 规约 §2.7 真机登记），
    这里提前拦下并指路，不把坏包流给用户。
    """
    probe_code = (
        "from PySide6 import QtCore, QtWidgets; "
        "import PySide6, os; print(os.path.dirname(PySide6.__file__))")
    result = subprocess.run([sys.executable, "-c", probe_code],
                            capture_output=True, text=True, cwd=ROOT)
    if result.returncode != 0:
        tail = (result.stderr or result.stdout or "").strip()[-300:]
        fail("当前 Python 环境的 PySide6 无法加载（" + tail + "）。\n"
             "最常见原因：在 conda 环境里用 pip 装了 PySide6（DLL 版本错配）。\n"
             "解决：改用项目自带虚拟环境执行打包——\n"
             "  .venv\\Scripts\\python.exe tools/package.py\n"
             "或先激活项目虚拟环境（.venv\\Scripts\\activate）；conda 环境请用\n"
             "  conda install -c conda-forge pyside6 替换 pip 版")
    location = result.stdout.strip()
    # conda 环境里的 pip 版 PySide6：import 靠 conda 的 DLL 环境能成功，
    # 但 PyInstaller 冻结后失去该上下文，产物必报 QtCore DLL load failed
    # （AGENT.md 规约 §2.7 真机登记）。用 conda-meta 有无 pyside6 记录区分
    # conda-forge 安装与 pip 安装。
    conda_meta = Path(sys.prefix) / "conda-meta"
    if conda_meta.is_dir():
        has_pyside6 = any(p.name.lower().startswith("pyside6")
                          for p in conda_meta.glob("*.json"))
        if not has_pyside6:
            fail("检测到在 conda 环境里用 pip 安装的 PySide6（conda-meta 无 pyside6 "
                 "记录）。这种组合 import 能成功，但 PyInstaller 冻结产物会报\n"
                 "  DLL load failed while importing QtCore\n"
                 "（DLL 依赖 conda 环境上下文）。解决：改用项目虚拟环境执行打包——\n"
                 "  .venv\\Scripts\\python.exe tools/package.py\n"
                 "或在该 conda 环境执行 pip uninstall pyside6 后\n"
                 "  conda install -c conda-forge pyside6")
    log(f"PySide6 运行时自检通过（{location}）")


def make_icons(*, dry_run: bool) -> dict[str, Path]:
    """用现有的 256px PNG 帧生成 ico / icns，避免为打包引入 Pillow。"""
    icons = {"windows": TMP / f"{APP}.ico", "macos": TMP / f"{APP}.icns"}
    if dry_run:
        return icons
    if not ICON_SOURCE.is_file():
        fail(f"图标素材缺失：{ICON_SOURCE}")
    png = ICON_SOURCE.read_bytes()
    if png[:8] != b"\x89PNG\r\n\x1a\n":
        fail(f"图标素材不是 PNG：{ICON_SOURCE}")
    size = struct.unpack(">I", png[16:20])[0]
    TMP.mkdir(parents=True, exist_ok=True)
    # ICO 允许直接内嵌 PNG；256 写成 0（单字节宽高字段的约定）
    icons["windows"].write_bytes(
        struct.pack("<HHH", 0, 1, 1)
        + struct.pack("<BBBBHHII", size & 0xFF, size & 0xFF, 0, 0, 1, 32, len(png), 22)
        + png)
    # ICNS：一个 PNG chunk 即可，类型按边长选 ic07/ic08/ic09
    kind = {128: b"ic07", 256: b"ic08", 512: b"ic09"}.get(size, b"ic08")
    chunk = kind + struct.pack(">I", len(png) + 8) + png
    icons["macos"].write_bytes(b"icns" + struct.pack(">I", len(chunk) + 8) + chunk)
    log(f"图标已生成（源帧 {size}x{size}）")
    return icons


def freeze(target: str, icon: Path, *, console: bool, dry_run: bool) -> None:
    cmd = [sys.executable, "-m", "PyInstaller",
           "--noconfirm", "--clean", "--onedir",
           "--name", APP,
           "--paths", str(ROOT / "src"),
           "--specpath", str(TMP),
           "--workpath", str(TMP / "build"),
           "--distpath", str(DIST),
           "--icon", str(icon),
           "--console" if console else "--windowed"]
    for module in EXCLUDE_MODULES:
        cmd += ["--exclude-module", module]
    # jieba 是惰性 import，且自带词典必须随包分发，否则分词能力静默退化
    if importlib.util.find_spec("jieba") is not None:
        cmd += ["--hidden-import", "jieba", "--collect-data", "jieba"]
    if target == "macos":
        cmd += ["--osx-bundle-identifier", BUNDLE_ID]
    cmd.append(str(ENTRY))
    log("冻结 Python + PySide6（onedir）")
    run(cmd, dry_run=dry_run)


def bundle_dir(target: str, *, dry_run: bool) -> Path:
    path = DIST / APP if target == "windows" else DIST / f"{APP}.app"
    if target == "macos" and not path.is_dir() and not dry_run:
        apps = sorted(DIST.glob("*.app"))
        if apps:
            path = apps[0]
    if dry_run:
        return path
    if not path.is_dir():
        fail(f"未找到冻结产物目录：{path}")
    exe = (path / f"{APP}.exe" if target == "windows"
           else path / "Contents" / "MacOS" / APP)
    if not exe.is_file():
        fail(f"未找到可执行文件：{exe}")
    return path


def asset_destination(target: str, bundle: Path) -> Path:
    """与 main.py::_runtime_root() 的冻结候选路径保持一致。"""
    if target == "windows":
        return bundle / "assets"
    resources = bundle / "Contents" / "Resources"
    base = resources if resources.is_dir() else bundle / "Contents" / "MacOS"
    return base / "assets"


def copy_assets(target: str, bundle: Path, *, dry_run: bool) -> None:
    destination = asset_destination(target, bundle)
    log(f"复制运行期素材 -> {destination}")
    if dry_run:
        return
    if destination.exists():
        shutil.rmtree(destination)
    shutil.copytree(ASSETS, destination)
    if not (destination / "pet" / "cat" / "idle" / "01.png").is_file():
        fail(f"素材复制后校验失败：{destination}")


def zip_bundle(bundle: Path, version: str, *, dry_run: bool) -> Path:
    archive = DIST / f"{APP}-{version}-windows-{arch()}.zip"
    log(f"生成便携包 {archive.name}")
    if dry_run:
        return archive
    # PNG / 图标本身已压缩，再做 DEFLATE 只烧 CPU 不减体积
    already_compressed = {".png", ".jpg", ".jpeg", ".ico", ".icns", ".zip", ".gz"}
    with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as zf:
        for path in sorted(bundle.rglob("*")):
            if not path.is_file():
                continue
            kind = (zipfile.ZIP_STORED if path.suffix.lower() in already_compressed
                    else zipfile.ZIP_DEFLATED)
            zf.write(path, Path(bundle.name) / path.relative_to(bundle),
                     compress_type=kind)
    return archive


def find_makensis() -> str | None:
    found = shutil.which("makensis")
    if found:
        return found
    for var, default in (("ProgramFiles(x86)", r"C:\Program Files (x86)"),
                         ("ProgramFiles", r"C:\Program Files")):
        candidate = Path(os.environ.get(var, default)) / "NSIS" / "makensis.exe"
        if candidate.is_file():
            return str(candidate)
    return None


def nsis_installer(bundle: Path, version: str, *, dry_run: bool) -> Path | None:
    makensis = find_makensis()
    if makensis is None:
        log("未检测到 NSIS (makensis)，跳过 setup.exe；安装 `choco install nsis` 后可生成")
        return None
    output = DIST / f"{APP}-{version}-windows-{arch()}-setup.exe"
    script = TMP / "installer.nsi"
    if not dry_run:
        script.write_text(
            NSIS_TEMPLATE.replace("@OUTFILE@", str(output))
                         .replace("@SOURCE@", str(bundle))
                         .replace("@VERSION@", version),
            encoding="ascii")
    log(f"生成 Windows 安装程序 {output.name}")
    run([makensis, "/V2", str(script)], dry_run=dry_run)
    return output


def sign_app(bundle: Path, *, dry_run: bool) -> None:
    identity = os.environ.get("WISEPET_CODESIGN_IDENTITY", "").strip()
    if not identity:
        return
    log("对 .app 签名（WISEPET_CODESIGN_IDENTITY）")
    run(["codesign", "--deep", "--force", "--options", "runtime",
         "--sign", identity, str(bundle)], dry_run=dry_run)


def sign_dmg(dmg: Path, *, dry_run: bool) -> None:
    """dmg 也要签，否则公证铁定失败（Apple 要求提交物本身带 runtime 签名）。"""
    identity = os.environ.get("WISEPET_CODESIGN_IDENTITY", "").strip()
    if not identity:
        return
    log("对 .dmg 签名（WISEPET_CODESIGN_IDENTITY）")
    run(["codesign", "--force", "--options", "runtime", "--sign", identity, str(dmg)],
        dry_run=dry_run)


def notarize_dmg(dmg: Path, *, dry_run: bool) -> None:
    """公证（可选，默认关闭）：在 CI secrets 配齐 Apple 凭据并置 WISEPET_NOTARIZE=1 才走。

    凭据走环境变量、永不落盘；dry-run 下只说明、绝不打印明文密码。
    没有 Apple Developer 账号的用户（或不配 secrets）整条链路自动跳过，
    产出未签名 dmg（双击报「无法验证开发者」，但可拖进 /Applications 用）。
    """
    if os.environ.get("WISEPET_NOTARIZE", "").strip() != "1":
        return
    if dry_run:
        log("公证已配置（WISEPET_NOTARIZE=1）；dry-run 下仅打印命令，不提交凭据")
    apple_id = os.environ.get("APPLE_ID", "").strip()
    password = os.environ.get("APPLE_APP_PASSWORD", "").strip()
    team = os.environ.get("APPLE_TEAM_ID", "").strip()
    if not (apple_id and password and team):
        log("未配置完整的 Apple 公证凭据（APPLE_ID/APPLE_APP_PASSWORD/APPLE_TEAM_ID），跳过")
        return
    log("提交公证（xcrun notarytool submit --wait）")
    run(["xcrun", "notarytool", "submit", str(dmg),
         "--apple-id", apple_id, "--password", password, "--team-id", team,
         "--wait"], dry_run=dry_run)
    log("装订公证票据（xcrun stapler staple）")
    run(["xcrun", "stapler", "staple", str(dmg)], dry_run=dry_run)


def dmg_installer(bundle: Path, version: str, *, dry_run: bool) -> Path:
    output = DIST / f"{APP}-{version}-macos-{arch()}.dmg"
    staging = TMP / "dmg"
    if not dry_run:
        if staging.exists():
            shutil.rmtree(staging)
        staging.mkdir(parents=True)
        shutil.copytree(bundle, staging / bundle.name, symlinks=True)
        (staging / "Applications").symlink_to(Path("/Applications"))
    log(f"生成 macOS 磁盘映像 {output.name}")
    run(["hdiutil", "create", "-volname", APP, "-srcfolder", str(staging),
         "-ov", "-format", "UDZO", str(output)], dry_run=dry_run)
    return output


def size_mb(path: Path) -> float:
    if not path.exists():
        return 0.0
    if path.is_dir():
        return sum(p.stat().st_size for p in path.rglob("*") if p.is_file()) / 1048576
    return path.stat().st_size / 1048576


def prune_bundle(bundle: Path) -> None:
    """冻结后修剪无用/混入的二进制（见 PRUNE_BINARIES / PRUNE_ROOT_GLOBS 注释）。

    修剪是"尽力而为"：文件不存在（版本升级改名）就跳过；启动自检与
    verify_bundle 兜底，剪坏了会以 exe 起不来暴露而不是静默流出。
    """
    removed = 0
    exact = {n.lower() for n in PRUNE_BINARIES}
    for path in list(bundle.rglob("*")):
        if path.is_file() and path.name.lower() in exact:
            path.unlink()
            removed += 1
        elif (path.is_dir() and path.parent.name == "plugins"
              and path.name in PRUNE_PLUGIN_DIRS):
            shutil.rmtree(path)
            removed += 1
    # conda PATH 混入的 DLL 只会落在 _internal 根目录：只清理根目录匹配项
    internal = bundle / "_internal"
    if internal.is_dir():
        for pattern in PRUNE_ROOT_GLOBS:
            for path in internal.glob(pattern):
                if path.is_file():
                    path.unlink()
                    removed += 1
    log(f"修剪无用 Qt 二进制/插件：移除 {removed} 项")


def verify_bundle(bundle: Path, target: str) -> dict:
    """产物自检：可执行文件、运行期素材、文件数与体积（CI / --verify 共用）。

    macOS 的 .app 内含大量 framework 符号链接（Versions/Current 等），
    `rglob` 会遍历到链接本身，`stat()` 又会跟着链接指向重复计一次体积。
    这里按「只算真实文件」去重，并按平台取阈值，避免误判健康产物。
    """
    exe = (bundle / f"{APP}.exe" if target == "windows"
           else bundle / "Contents" / "MacOS" / APP)
    icon = asset_destination(target, bundle) / "pet" / "cat" / "idle" / "01.png"
    files = [p for p in bundle.rglob("*") if p.is_file() and not p.is_symlink()]
    size = sum(p.stat().st_size for p in files) / 1048576
    max_files = MAX_BUNDLE_FILES_MACOS if target == "macos" else MAX_BUNDLE_FILES
    max_mb = MAX_BUNDLE_MB_MACOS if target == "macos" else MAX_BUNDLE_MB
    report = {"exe": exe.is_file(), "assets": icon.is_file(),
              "files": len(files), "size_mb": round(size, 2),
              "max_files": max_files, "max_mb": max_mb}
    report["ok"] = (report["exe"] and report["assets"]
                    and len(files) <= max_files
                    and size <= max_mb)
    return report


def clean(version: str) -> None:
    for path in (TMP, DIST / APP, DIST / f"{APP}.app"):
        if path.is_dir():
            shutil.rmtree(path)
        elif path.exists():
            path.unlink()
    # 历史解压目录（如 dist/WisePet-v1.8/）与所有旧版本包一并清掉：
    # 旧实现只按当前版本号删文件，这些目录会被 CI 的 dist/WisePet-* 通配上传，越积越大
    for path in DIST.glob(f"{APP}-*"):
        if path.is_dir():
            shutil.rmtree(path)
        elif path.is_file():
            path.unlink()
    log("已清理临时文件与历史产物（含旧解压目录）")


def main() -> int:
    parser = argparse.ArgumentParser(description="WisePet Windows / macOS 打包程序")
    parser.add_argument("--target", choices=("auto", "windows", "macos"), default="auto",
                        help="目标平台，默认取当前系统")
    parser.add_argument("--no-installer", action="store_true",
                        help="只冻结，不生成 zip / setup.exe / dmg")
    parser.add_argument("--console", action="store_true",
                        help="冻结时保留控制台窗口（排查启动失败用）")
    parser.add_argument("--dry-run", action="store_true", help="只打印将执行的命令")
    parser.add_argument("--clean", action="store_true", help="清理临时文件与历史产物")
    parser.add_argument("--verify", action="store_true",
                        help="只检查已有冻结产物（exe / 素材 / 文件数 / 体积），不重新打包")
    args = parser.parse_args()

    version = app_version()
    if args.clean:
        clean(version)
        return 0

    current = current_platform()
    target = current if args.target == "auto" else args.target
    if current not in ("windows", "macos"):
        fail("仅支持在 Windows / macOS 上打包（Linux 不在项目支持范围内）")
    if target != current and not args.dry_run:
        fail(f"PyInstaller 不支持交叉编译：{target} 包请在 {target} 机器上运行本脚本，"
             "或使用 .github/workflows/build.yml 的双平台 CI")
    log(f"目标 {target} / 架构 {arch()} / 版本 {version}"
        + ("（dry-run）" if args.dry_run else ""))

    if args.verify:
        report = verify_bundle(bundle_dir(target, dry_run=False), target)
        log(f"产物自检：{report}")
        return 0 if report["ok"] else 1

    if not args.dry_run:
        ensure_project_venv()
        preflight_runtime()
        if importlib.util.find_spec("PyInstaller") is None:
            fail("缺少 PyInstaller：请先执行 pip install -r dev-requirements.txt")
        TMP.mkdir(parents=True, exist_ok=True)
        DIST.mkdir(parents=True, exist_ok=True)
        for stale in (DIST / APP, DIST / f"{APP}.app"):
            if stale.is_dir():
                shutil.rmtree(stale)

    icons = make_icons(dry_run=args.dry_run)
    freeze(target, icons[target], console=args.console, dry_run=args.dry_run)
    bundle = bundle_dir(target, dry_run=args.dry_run)
    copy_assets(target, bundle, dry_run=args.dry_run)
    if not args.dry_run:
        prune_bundle(bundle)

    artifacts: list[Path] = [bundle]
    if not args.no_installer:
        if target == "windows":
            artifacts.append(zip_bundle(bundle, version, dry_run=args.dry_run))
            installer = nsis_installer(bundle, version, dry_run=args.dry_run)
            if installer is not None:
                artifacts.append(installer)
        else:
            sign_app(bundle, dry_run=args.dry_run)
            dmg = dmg_installer(bundle, version, dry_run=args.dry_run)
            sign_dmg(dmg, dry_run=args.dry_run)
            notarize_dmg(dmg, dry_run=args.dry_run)
            artifacts.append(dmg)

    if not args.dry_run:
        report = verify_bundle(bundle, target)
        log(f"产物自检：exe={report['exe']} assets={report['assets']} "
            f"files={report['files']}/{report['max_files']} "
            f"size={report['size_mb']}/{report['max_mb']}MB target={target}")
        if not report["ok"]:
            fail("产物自检失败：缺可执行文件/素材，或文件数与体积超过阈值"
                 f"（files {report['files']}/{report['max_files']}，"
                 f"size {report['size_mb']}/{report['max_mb']}MB）")
        shutil.rmtree(TMP, ignore_errors=True)
    log("产物：")
    for path in artifacts:
        print(f"  - {path}" + ("" if args.dry_run else f"（{size_mb(path):.1f} MB）"),
              flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
